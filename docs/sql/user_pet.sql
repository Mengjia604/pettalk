CREATE DATABASE pettalk DEFAULT CHARACTER SET utf8mb4;

USE pettalk;

CREATE TABLE user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  openid VARCHAR(64) UNIQUE,
  nickname VARCHAR(50),
  avatar VARCHAR(255),
  bio VARCHAR(200),
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pet (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT NOT NULL,
  name VARCHAR(50),
  breed VARCHAR(50),
  birthday DATE,
  avatar VARCHAR(255),
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP
);